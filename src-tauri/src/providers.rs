use crate::models::{AiSettings, AiStreamEvent, StructuredContext};
use futures_util::StreamExt;
use reqwest::Client;
use serde_json::{json, Value};
use std::collections::HashSet;
use std::sync::{Arc, Mutex};
use std::time::Duration;
use tauri::{AppHandle, Emitter};

const AI_EVENT: &str = "aster://ai-stream";

pub async fn stream_response(
    app: AppHandle,
    request_id: String,
    settings: AiSettings,
    context: StructuredContext,
    api_key: Option<String>,
    cancelled: Arc<Mutex<HashSet<String>>>,
) -> Result<(), String> {
    match settings.provider.as_str() {
        "mock" => stream_mock(app, request_id, context, cancelled).await,
        "openai" => stream_openai(app, request_id, settings, context, api_key, cancelled).await,
        "gemini" => stream_gemini(app, request_id, settings, context, api_key, cancelled).await,
        "claude" => stream_claude(app, request_id, settings, context, api_key, cancelled).await,
        _ => Err("Select Mock, OpenAI, Gemini, or Claude in Settings.".to_string()),
    }
}

pub async fn health_check(provider: &str, api_key: Option<String>) -> Result<(), String> {
    if provider == "mock" {
        return Ok(());
    }
    let key = required_key(api_key, provider)?;
    let response = match provider {
        "openai" => client()?.get("https://api.openai.com/v1/models").bearer_auth(key).send().await,
        "gemini" => client()?.get("https://generativelanguage.googleapis.com/v1beta/models").header("x-goog-api-key", key).send().await,
        "claude" => client()?.get("https://api.anthropic.com/v1/models").header("x-api-key", key).header("anthropic-version", "2023-06-01").send().await,
        _ => return Err("Select Mock, OpenAI, Gemini, or Claude in Settings.".to_string()),
    }.map_err(|_| format!("{provider} is unreachable. Check your network and try again."))?;
    if response.status().is_success() {
        Ok(())
    } else {
        Err(format!("{provider} returned {}. Check the API key and account access.", response.status()))
    }
}

fn is_cancelled(cancelled: &Arc<Mutex<HashSet<String>>>, request_id: &str) -> bool {
    cancelled.lock().map(|items| items.contains(request_id)).unwrap_or(true)
}

fn emit(app: &AppHandle, request_id: &str, delta: impl Into<String>, done: bool, error: Option<String>) {
    let _ = app.emit(AI_EVENT, AiStreamEvent {
        request_id: request_id.to_string(),
        delta: delta.into(),
        done,
        error,
    });
}

fn system_prompt() -> &'static str {
    "You are Aster, a privacy-first desktop productivity assistant. Be helpful, concise, accurate, and transparent about uncertainty. Do not claim access to information not provided in context."
}

fn prompt_from_context(context: &StructuredContext) -> String {
    let transcript = if context.recent_transcript.is_empty() {
        "(none)".to_string()
    } else {
        context.recent_transcript.join("\n")
    };
    format!(
        "Current question:\n{}\n\nRecent transcript:\n{}\n\nConversation summary:\n{}\n\nScreen context (only if enabled by the user):\nApplication: {}\nTitle: {}\nVisible text: {}\nTopics: {}\n\nTask context:\n{}",
        context.current_question,
        transcript,
        context.conversation_summary,
        context.screen_context.application,
        context.screen_context.window_title,
        context.screen_context.visible_text,
        context.screen_context.detected_topics.join(", "),
        context.task_context,
    )
}

async fn stream_mock(
    app: AppHandle,
    request_id: String,
    context: StructuredContext,
    cancelled: Arc<Mutex<HashSet<String>>>,
) -> Result<(), String> {
    let question = if context.current_question.trim().is_empty() {
        "your request"
    } else {
        context.current_question.trim()
    };
    let answer = format!(
        "Here is a focused starting point for {question}:\n\n• Clarify the goal and constraints first.\n• Use the transcript and screen context only where they are relevant.\n• Break the next action into a small, verifiable step.\n\nThis response is generated by Aster's local mock provider, so no cloud request was made."
    );
    for chunk in answer.chars().collect::<Vec<_>>().chunks(12) {
        if is_cancelled(&cancelled, &request_id) {
            emit(&app, &request_id, "", true, None);
            return Ok(());
        }
        emit(&app, &request_id, chunk.iter().collect::<String>(), false, None);
        tokio::time::sleep(Duration::from_millis(24)).await;
    }
    emit(&app, &request_id, "", true, None);
    Ok(())
}

fn required_key(api_key: Option<String>, provider: &str) -> Result<String, String> {
    api_key.filter(|key| !key.trim().is_empty()).ok_or_else(|| format!("Add a {provider} API key in Settings."))
}

fn client() -> Result<Client, String> {
    Client::builder()
        .connect_timeout(Duration::from_secs(10))
        .timeout(Duration::from_secs(45))
        .build()
        .map_err(|_| "Unable to initialize a secure network client.".to_string())
}

async fn stream_openai(
    app: AppHandle,
    request_id: String,
    settings: AiSettings,
    context: StructuredContext,
    api_key: Option<String>,
    cancelled: Arc<Mutex<HashSet<String>>>,
) -> Result<(), String> {
    let key = required_key(api_key, "OpenAI")?;
    let response = client()?
        .post("https://api.openai.com/v1/chat/completions")
        .bearer_auth(key)
        .json(&json!({
            "model": settings.model,
            "stream": true,
            "temperature": settings.temperature,
            "max_tokens": settings.max_output,
            "messages": [
                {"role": "system", "content": system_prompt()},
                {"role": "user", "content": prompt_from_context(&context)}
            ]
        }))
        .send().await.map_err(|_| "OpenAI is unreachable. Check your network and try again." )?;
    if !response.status().is_success() {
        return Err(format!("OpenAI returned {}.", response.status()));
    }
    stream_sse(response, app, request_id, cancelled, |value| {
        value.pointer("/choices/0/delta/content").and_then(Value::as_str).map(ToString::to_string)
    }).await
}

async fn stream_gemini(
    app: AppHandle,
    request_id: String,
    settings: AiSettings,
    context: StructuredContext,
    api_key: Option<String>,
    cancelled: Arc<Mutex<HashSet<String>>>,
) -> Result<(), String> {
    let key = required_key(api_key, "Gemini")?;
    let model = if settings.model.trim().is_empty() { "gemini-3.6-flash" } else { settings.model.trim() };
    let response = client()?
        .post(format!("https://generativelanguage.googleapis.com/v1beta/models/{model}:streamGenerateContent?alt=sse"))
        .header("x-goog-api-key", key)
        .json(&json!({
            "systemInstruction": {"parts": [{"text": system_prompt()}]},
            "contents": [{"role": "user", "parts": [{"text": prompt_from_context(&context)}]}],
            "generationConfig": {"maxOutputTokens": settings.max_output}
        }))
        .send().await.map_err(|_| "Gemini is unreachable. Check your network and try again." )?;
    if !response.status().is_success() {
        return Err(format!("Gemini returned {}. Check your model and API key.", response.status()));
    }
    stream_sse(response, app, request_id, cancelled, |value| {
        value.pointer("/candidates/0/content/parts/0/text").and_then(Value::as_str).map(ToString::to_string)
    }).await
}

async fn stream_claude(
    app: AppHandle,
    request_id: String,
    settings: AiSettings,
    context: StructuredContext,
    api_key: Option<String>,
    cancelled: Arc<Mutex<HashSet<String>>>,
) -> Result<(), String> {
    let key = required_key(api_key, "Claude")?;
    let response = client()?
        .post("https://api.anthropic.com/v1/messages")
        .header("x-api-key", key)
        .header("anthropic-version", "2023-06-01")
        .json(&json!({
            "model": settings.model,
            "max_tokens": settings.max_output,
            "stream": true,
            "system": system_prompt(),
            "messages": [{"role": "user", "content": prompt_from_context(&context)}]
        }))
        .send().await.map_err(|_| "Claude is unreachable. Check your network and try again." )?;
    if !response.status().is_success() {
        return Err(format!("Claude returned {}. Check your model and API key.", response.status()));
    }
    stream_sse(response, app, request_id, cancelled, |value| {
        if value.get("type").and_then(Value::as_str) == Some("content_block_delta") {
            value.pointer("/delta/text").and_then(Value::as_str).map(ToString::to_string)
        } else {
            None
        }
    }).await
}

async fn stream_sse<F>(
    response: reqwest::Response,
    app: AppHandle,
    request_id: String,
    cancelled: Arc<Mutex<HashSet<String>>>,
    extract: F,
) -> Result<(), String>
where
    F: Fn(&Value) -> Option<String>,
{
    let mut stream = response.bytes_stream();
    let mut buffer = String::new();
    while let Some(next) = stream.next().await {
        if is_cancelled(&cancelled, &request_id) {
            emit(&app, &request_id, "", true, None);
            return Ok(());
        }
        let bytes = next.map_err(|_| "The provider stream ended unexpectedly.".to_string())?;
        buffer.push_str(&String::from_utf8_lossy(&bytes));
        while let Some(line_end) = buffer.find('\n') {
            let line = buffer[..line_end].trim().to_string();
            buffer.drain(..=line_end);
            let Some(data) = line.strip_prefix("data:") else { continue };
            let data = data.trim();
            if data == "[DONE]" { continue; }
            if let Ok(value) = serde_json::from_str::<Value>(data) {
                if let Some(delta) = extract(&value) {
                    emit(&app, &request_id, delta, false, None);
                }
            }
        }
    }
    emit(&app, &request_id, "", true, None);
    Ok(())
}
